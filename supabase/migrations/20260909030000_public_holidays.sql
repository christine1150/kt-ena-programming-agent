-- 공휴일 캘린더 신설(2026-09-09, 사용자 지시)
--
-- 배경: 사용자가 "주요시간(프라임)"을 요일에 따라 다르게 정의했다 —
--   평일 19~23시, 토·일·공휴일 18~23시.
-- 그런데 이 프로젝트에는 공휴일 테이블·목록·달력이 전혀 없었다(실측: information_schema
-- 조회 0건, 저장소 전체 grep 0건). 기존에 공휴일 왜곡에 대응하던 유일한 방법은 같은 요일끼리
-- 비교하는 SDoW 방식뿐이었다. 프라임을 요일 기준으로 가르려면 "그날이 공휴일인가"를 실제로
-- 알아야 하므로 이 테이블을 신설한다.
--
-- 정직하게 밝히는 한계: 아래 시드 중 음력 기반 공휴일(설날·추석·부처님오신날)과 대체공휴일은
-- 천문 계산이 아니라 알려진 날짜를 옮겨 적은 것이다. 배포 후 사용자에게 전체 목록을 제시해
-- 검수받고, 관리자 화면에서 직접 수정·추가할 수 있게 한다. 미등록 날짜는 추정하지 않고
-- 평일로 처리한다(억지 추정 금지 — CLAUDE.md No Hallucination).
--
-- 대체공휴일 규정 메모(시드 근거):
--   · 삼일절·광복절·개천절·한글날·어린이날·부처님오신날·성탄절 → 토요일 또는 일요일과 겹치면 대체
--   · 설날·추석 연휴 → 일요일 또는 다른 공휴일과 겹칠 때만 대체(토요일 겹침은 대상 아님)
--   · 현충일 → 대체공휴일 대상이 아님
--   예: 2026 추석 연휴는 9/24(목)~9/26(토)로 토요일과 겹치지만, 설·추석은 토요일 겹침이
--       대체 대상이 아니므로 대체공휴일을 넣지 않았다(2023년 추석도 같은 사유로 대체공휴일이
--       아니라 별도 임시공휴일이 지정됐다).

create table if not exists public_holidays (
  holiday_date date primary key,
  name text not null,
  -- legal: 법정공휴일 / substitute: 대체공휴일 / temporary: 임시공휴일(선거일·국경일 지정 등)
  kind text not null check (kind in ('legal', 'substitute', 'temporary')),
  note text,
  updated_at timestamptz not null default now()
);

comment on table public_holidays is
  '한국 공휴일 캘린더. 프라임(주요시간) 판정에서 토·일과 동일하게 취급된다. 음력 명절·대체공휴일은 사용자 검수 대상.';

alter table public_holidays enable row level security;

drop policy if exists public_holidays_read on public_holidays;
create policy public_holidays_read on public_holidays for select using (true);

grant select on public_holidays to anon, authenticated;

-- 그날이 "주말처럼" 다뤄져야 하는 날인지 — 토·일이거나 공휴일.
-- 프라임 판정에서 평일(19~23시)과 주말·공휴일(18~23시)을 가르는 유일한 기준이다.
create or replace function is_weekendlike_date(p_date date)
returns boolean
language sql
stable
as $$
  select extract(isodow from p_date) >= 6
      or exists (select 1 from public_holidays h where h.holiday_date = p_date)
$$;

comment on function is_weekendlike_date(date) is
  '토·일 또는 공휴일이면 true. 프라임 시간 판정(평일 19~23시 / 주말·공휴일 18~23시)의 기준.';

