export function seasonOf(month: number, southern: boolean): string {
  const n = month === 12 || month <= 2 ? "겨울" : month <= 5 ? "봄" : month <= 8 ? "여름" : "가을";
  if (!southern) return n;
  return { 겨울: "여름", 여름: "겨울", 봄: "가을", 가을: "봄" }[n]!;
}
